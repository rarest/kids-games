export function routePoint(id, t) {
  const nodes = ROUTE_POINTS[id];
  if (!nodes) return null;
  const n = nodes.length,
    x = t * n,
    i = Math.floor(x) % n,
    f = x - Math.floor(x);
  return [0, 1, 2].map((axis) => {
    const a = nodes[(i - 1 + n) % n][axis],
      b = nodes[i][axis],
      c = nodes[(i + 1) % n][axis],
      d = nodes[(i + 2) % n][axis];
    const f2 = f * f,
      f3 = f2 * f;
    return (
      ((1 - 3 * f + 3 * f2 - f3) * a +
        (4 - 6 * f2 + 3 * f3) * b +
        (1 + 3 * f + 3 * f2 - 3 * f3) * c +
        f3 * d) /
      6
    );
  });
}
