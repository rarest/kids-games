import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve,join} from 'node:path';
if(!process.argv[2])throw Error('Usage: node scripts/import-butterfly.mjs SOURCE_DIR [SITE_DIR]');
const source=resolve(process.argv[2]);
const dest=resolve(process.argv[3]||new URL('../',import.meta.url).pathname);
const names=['index.html','rules.js','server.cjs','checkpoint.js','vegetation.js'];
const content=await Promise.all(names.map(name=>readFile(join(source,name))));
let html=content[0].toString();
if(!html.includes('GARDEN_WS_PATH'))throw Error('Source must support GARDEN_WS_PATH before public import');
if(!html.includes('回到小火箭游戏厅'))throw Error('Source must include game hall navigation');
html=html.replace('<body>','<body>\n<script>globalThis.GARDEN_WS_PATH=\'/butterfly-ws\';</script>').replace('蜜语花园 · 本地试玩','蜜语花园 · 小火箭游戏厅');
await mkdir(join(dest,'games'),{recursive:true});await mkdir(join(dest,'butterfly'),{recursive:true});
await writeFile(join(dest,'games/butterfly.html'),html);
for(let i=1;i<names.length;i++)await writeFile(join(dest,'butterfly',names[i]),content[i]);
await writeFile(join(dest,'butterfly/package.json'),JSON.stringify({private:true,type:'commonjs'},null,2)+'\n');
const manifest={source:'products/butterfly-garden',files:names.map((name,i)=>({name,sha256:createHash('sha256').update(content[i]).digest('hex')})),publicPage:{path:'games/butterfly.html',sha256:createHash('sha256').update(html).digest('hex')}};
await writeFile(join(dest,'butterfly/source-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(`Imported ${names.length} frozen source files; public page ${manifest.publicPage.sha256}`);
